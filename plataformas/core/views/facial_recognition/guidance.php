    <div>
        <strong>Recomendaciones para una captura confiable</strong>
        <ul class="mb-0 mt-2 ps-3">
            <li>Ubica el rostro de frente, centrado y visible dentro del encuadre.</li>
            <li>Usa iluminación frontal uniforme; evita contraluz, sombras fuertes y reflejos.</li>
            <li>Retira lentes oscuros, gorros o elementos que oculten el rostro.</li>
            <li>Debe aparecer una sola persona y la imagen debe estar enfocada.</li>
            <li>Durante la prueba, sigue la instrucción y mueve suavemente la cabeza cuando se solicite.</li>
        </ul>
    </div>
